package model

import "math"

type Apogee struct{}

func (a *Apogee) Freq(tone float64, offset *uint32) uint16 {
	*offset = 0

	note := int(tone)
	if tone >= 12 {
		note -= 12
	}

	half := tone - math.Trunc(tone)

	if half > 0.5 {
		note++
		half -= 1.0
	}

	pitch := int(half*32) + 32

	note += pitch / 32
	note--

	scale := note % 12
	oct := note / 12

	freq := apogeeFreqs[pitch%32][scale]

	for oct > 7 {
		*offset++
		oct--
	}

	return uint16(oct<<10 | freq)
}

func apogeeLevel(volume *OPLModel) int {
	vol := volume.Get(OPLChanVolume)
	exp := volume.Get(OPLChanExpression)
	mv := volume.Get(OPLMasterVolume)

	return min(vol*exp*mv/16129, 127)
}

// apogeeTL maps a total level through the Apogee velocity/volume formula.
func apogeeTL(level, vel, tl int) int {
	x := (63 - tl) * (vel + 0x80)

	return ((level * x) >> 15) ^ 63
}

// Volume is the original Apogee model. Its AM voices bug makes the modulator
// of 2-op voices follow the already updated carrier level.
func (a *Apogee) Volume(volume *OPLModel) {
	level := apogeeLevel(volume)
	vel := volume.Get(OPLVelocity)
	mod, car := volume.Get(OPLModN), volume.Get(OPLCarN)

	if volume.IsCar() {
		car = apogeeTL(level, vel, car)
		volume.Set(OPLCarN, car)
	}

	if volume.IsMod() {
		x := (63 - mod) * (vel + 0x80)

		// The bug is not reproduced on 4-op voices.
		if volume.Get(OPLVoiceMode) <= OPLVoice_MODE_2op_AM {
			x = car
		}

		volume.Set(OPLModN, ((level*x)>>15)^63)
	}
}

// ApogeeFixed is Apogee with the AM voices bug fixed.
type ApogeeFixed struct{ Apogee }

func (a *ApogeeFixed) Volume(volume *OPLModel) {
	level := apogeeLevel(volume)
	vel := volume.Get(OPLVelocity)

	if volume.IsCar() {
		volume.Set(OPLCarN, apogeeTL(level, vel, volume.Get(OPLCarN)))
	}

	if volume.IsMod() {
		volume.Set(OPLModN, apogeeTL(level, vel, volume.Get(OPLModN)))
	}
}

