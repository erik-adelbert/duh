package model

import "math"

type Ail struct{}

func (a *Ail) Freq(tone float64, offset *uint32) uint16 {
	*offset = 0

	note := int(tone)
	half := tone - math.Trunc(tone)

	if half > 0.5 {
		note++
		half -= 1.0
	}

	pitch := int(half*4096) + 8192 // midi standard pitch
	pitch = ((pitch - 0x2000) / 0x20) * 2

	var off int

	note -= 12

	for note < 0 {
		note += 12
		off--
	}

	for note > 95 {
		note -= 12
		off++
	}

	pitch += (note&0xFF)<<8 + 8
	pitch /= 16

	for pitch < 12*16 {
		pitch += 12 * 16
	}

	for pitch > 96*16-1 {
		pitch -= 12 * 16
	}

	freq := ailFreqs[ailHalftones[pitch>>4]<<4+(pitch&0x0F)]
	oct := ailOctaves[pitch>>4]

	if freq&0x8000 == 0 {
		if oct > 0 {
			oct--
		} else {
			freq /= 2
		}
	}

	freq &= 0x3ff
	oct += off

	for oct > 7 {
		*offset++
		oct--
	}

	return uint16(oct<<10 | freq)
}

func (a *Ail) Volume(volume *OPLModel) {
	vol := volume.Get(OPLChanVolume)
	exp := volume.Get(OPLChanExpression)

	v := (vol * exp * 2) >> 8
	if v != 0 {
		v++
	}

	vel := ailVelocity[(volume.Get(OPLVelocity)&0x7F)>>3]

	v = (v * vel * 2) >> 8
	if v != 0 {
		v++
	}

	if mv := volume.Get(OPLMasterVolume); mv < 127 {
		v = v * mv / 127
	}

	v = min(v, 127)

	v0 := ^volume.Get(OPLModN) & 0x3F
	v1 := ^volume.Get(OPLCarN) & 0x3F

	if volume.IsMod() {
		v0 = v0 * v / 127
	}

	if volume.IsCar() {
		v1 = v1 * v / 127
	}

	volume.Set(OPLModN, ^v0&0x3F)
	volume.Set(OPLCarN, ^v1&0x3F)
}

